export function keywordsAfter(clause: string, dialect: Dialect): string[] {
  const words = [...(AFTER[clause] ?? AFTER['WHERE']), ...(ALSO[dialect][clause] ?? [])];
  return words.filter((w) => !NOT_IN[dialect].includes(w));
}

