fn firebird_refuses_a_wrong_password_and_an_unknown_database() {
    let e = connect(&profile(), Some(&Secret::new("nope")), &|| false)
        .err()
        .unwrap();
    assert_eq!(e.code, ErrorCode::AuthFailed, "{}", e.message);
    assert!(!e.message.contains("nope"));
    let mut p = profile();
    p.database = "/var/lib/firebird/data/no_such.fdb".into();
    let e = connect(&p, Some(&Secret::new(PW)), &|| false)
        .err()
        .unwrap();
    assert!(
        matches!(e.code, ErrorCode::NotFound | ErrorCode::InvalidQuery),
        "{:?} {}",
        e.code,
        e.message
    );
    let mut closed = profile();
    closed.port = 23051;
    let e = connect(&closed, Some(&Secret::new(PW)), &|| false)
        .err()
        .unwrap();
    assert_eq!(e.code, ErrorCode::ConnectionFailed);
    // there are no certificates to check
    let mut tls = profile();
    tls.tls = TlsMode::Verify;
    let e = connect(&tls, Some(&Secret::new(PW)), &|| false)
        .err()
        .unwrap();
    assert_eq!(e.code, ErrorCode::InvalidProfile);
    // its own encryption, asked for
    let mut crypt = profile();
    crypt.tls = TlsMode::Require;
    let mut s = connect(&crypt, Some(&Secret::new(PW)), &|| false).unwrap();
    assert_eq!(
        rows(&run(&mut s, "SELECT 1 FROM rdb$database")),
        json!([[1]])
    );
}

#[test]
#[ignore]
fn a_statement_stops_or_runs_out_of_time_and_the_session_goes_on() {
    const SLOW: &str =
        "SELECT COUNT(*) FROM rdb$fields a, rdb$fields b, rdb$fields c, rdb$fields d";
    let mut s = open();
    let stop = AtomicBool::new(false);
    let started = Instant::now();
    let r = std::thread::scope(|scope| {
        scope.spawn(|| {
            std::thread::sleep(Duration::from_millis(400));
            stop.store(true, Ordering::Relaxed);
        });
        s.query(SLOW, Limits::rows(1), &|| stop.load(Ordering::Relaxed))
    });
    assert_eq!(r.unwrap_err().code, ErrorCode::Cancelled);
    assert!(
        started.elapsed() < Duration::from_secs(8),
        "{:?}",
        started.elapsed()
    );
    assert!(s.is_open());
    assert_eq!(
        rows(&run(&mut s, "SELECT 1 FROM rdb$database")),
        json!([[1]])
    );
    let started = Instant::now();
    let late = s.query(
        SLOW,
        Limits {
            max_rows: 1,
            timeout: Some(Duration::from_secs(1)),
        },
        &|| false,
    );
    assert_eq!(late.unwrap_err().code, ErrorCode::Timeout);
    assert!(started.elapsed() < Duration::from_secs(8));
    assert_eq!(
        rows(&run(&mut s, "SELECT 2 FROM rdb$database")),
        json!([[2]])
    );
}

#[test]
#[ignore]
fn firebird_binds_values_and_a_read_only_session_cannot_write() {
    let mut s = open();
    let p = "SC_FB";
    shop(&mut s, p);
    let evil = "'; DROP TABLE SC_FB_CUSTOMER; --";
    let inserted = bound(
        &mut s,
        &format!("INSERT INTO {p}_CUSTOMER (ID, NAME, NOTE) VALUES (?, ?, ?)"),
        &[
            Bind::Int("7".into()),
            Bind::Text(evil.into()),
            Bind::Text("C:\\temp\ta\nb 🚀 \\'".into()),
        ],
    );
    assert_eq!(inserted.rows_affected, Some(1));
    let back = bound(
        &mut s,
        &format!("SELECT NAME, NOTE FROM {p}_CUSTOMER WHERE ID = ? AND NAME = ?"),
        &[Bind::Int("7".into()), Bind::Text(evil.into())],
    );
    assert_eq!(rows(&back), json!([[evil, "C:\\temp\ta\nb 🚀 \\'"]]));
    // a value is what its place is: a date, an exact number
    let typed = bound(
        &mut s,
        &format!("SELECT ID FROM {p}_ORDER WHERE PLACED_AT >= ? AND TOTAL < ? ORDER BY ID"),
        &[
            Bind::Date("2026-02-01".into()),
            Bind::Decimal("100.50".into()),
        ],
    );
    assert_eq!(rows(&typed), json!([[2]]));
    bound(
        &mut s,
        &format!("UPDATE {p}_ORDER SET TOTAL = ? WHERE ID = ?"),
        &[Bind::Decimal("1234567.89".into()), Bind::Int("3".into())],
    );
    assert_eq!(
        rows(&run(
            &mut s,
            &format!("SELECT TOTAL FROM {p}_ORDER WHERE ID = 3")
        )),
        json!([["1234567.89"]])
    );
    // what is no number, or has more places than the column keeps, never reaches the server
    for bad in ["1); DROP TABLE x; --", "1.234", "abc"] {
        let e = try_bound(
            &mut s,
            &format!("UPDATE {p}_ORDER SET TOTAL = ? WHERE ID = 3"),
            &[Bind::Decimal(bad.into())],
        )
        .unwrap_err();
        assert_eq!(e.code, ErrorCode::InvalidQuery, "{bad}: {}", e.message);
    }
    assert!(
        try_bound(
            &mut s,
            "SELECT 1 FROM rdb$database",
            &[Bind::Int("1".into())]
        )
        .is_err()
    );
    // the app's own questions bind text; names come without the blanks of their CHAR
    let asked = s
        .ask(
            "SELECT r.rdb$relation_name FROM rdb$relations r WHERE r.rdb$relation_name = ?",
            &["SC_FB_ORDER"],
            Some(Duration::from_secs(10)),
            &|| false,
        )
        .unwrap();
    assert_eq!(asked, vec![vec![Some("SC_FB_ORDER".to_owned())]]);

    // read only: every transaction of the session is one that cannot write
    let mut reader = open();
    assert!(reader.make_read_only());
    assert_eq!(
        rows(&run(
            &mut reader,
            &format!("SELECT COUNT(*) FROM {p}_CUSTOMER")
        )),
        json!([[3]])
    );
    for attempt in [
        format!("INSERT INTO {p}_CUSTOMER (ID, NAME) VALUES (99, 'x')"),
        format!("DELETE FROM {p}_ORDER"),
        format!("CREATE TABLE {p}_NEW (A INTEGER)"),
        format!("DROP TABLE {p}_ORDER"),
        format!("EXECUTE BLOCK AS BEGIN DELETE FROM {p}_ORDER; END"),
    ] {
        let e = try_run(&mut reader, &attempt).unwrap_err();
        assert!(
            matches!(
                e.code,
                ErrorCode::PermissionDenied | ErrorCode::InvalidQuery
            ),
            "{attempt}: {e}"
        );
    }
    // also in a transaction the user opens, whatever it is called
    run(&mut reader, "SET TRANSACTION READ WRITE");
    assert!(try_run(&mut reader, &format!("DELETE FROM {p}_ORDER")).is_err());
    run(&mut reader, "ROLLBACK");
    assert_eq!(
        rows(&run(
            &mut reader,
            &format!("SELECT COUNT(*) FROM {p}_ORDER")
        )),
        json!([[3]])
    );
    drop(reader);
    unshop(&mut s, p);
}

