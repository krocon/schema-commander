#[test]
#[ignore]
fn firebird_changes_limits_errors_and_transactions() {
    let mut s = open();
    let mut other = open();
    let stop = &|| false;
    let p = "SC_FA";
    shop(&mut s, p);
    let inserted = run(
        &mut s,
        &format!("INSERT INTO {p}_CUSTOMER (ID, NAME) VALUES (3, 'it''s; fine')"),
    );
    assert_eq!(inserted.rows_affected, Some(1));
    assert!(inserted.columns.is_empty());
    // kept as it ran: another session sees it
    assert_eq!(
        rows(&run(
            &mut other,
            &format!("SELECT NAME, COUNTRY FROM {p}_CUSTOMER WHERE ID = 3")
        )),
        json!([["it's; fine", "DE"]])
    );
    let empty = run(&mut s, &format!("SELECT * FROM {p}_CUSTOMER WHERE 1 = 0"));
    assert_eq!(empty.columns.len(), 4);
    assert!(empty.rows.is_empty());
    let cut = s
        .query(
            "SELECT a.rdb$field_name FROM rdb$fields a, rdb$fields b",
            Limits::rows(5),
            stop,
        )
        .unwrap();
    assert!(cut.truncated && cut.rows.len() == 5);
    assert_eq!(
        rows(&run(&mut s, "SELECT 1 FROM rdb$database")),
        json!([[1]])
    );

    let syntax = try_run(&mut s, "SELECT 1\n  FRM rdb$database").unwrap_err();
    assert_eq!(syntax.code, ErrorCode::InvalidQuery, "{}", syntax.message);
    let d = syntax.details.unwrap();
    assert_eq!(d.line, Some(2), "{}", syntax.message);
    assert!(d.position.is_some());
    let unknown = try_run(&mut s, "SELECT * FROM SC_FA_NOPE").unwrap_err();
    assert!(
        unknown.message.contains("SC_FA_NOPE"),
        "{}",
        unknown.message
    );
    let twice = try_run(
        &mut s,
        &format!("INSERT INTO {p}_CUSTOMER (ID, NAME) VALUES (3, 'x')"),
    )
    .unwrap_err();
    assert_eq!(twice.code, ErrorCode::InvalidQuery);
    assert!(s.is_open());

    // a transaction of the user: held until it is ended, unseen by others meanwhile
    run(&mut s, "SET TRANSACTION");
    assert_eq!(s.transaction_state(stop), TxState::Active);
    run(
        &mut s,
        &format!("INSERT INTO {p}_CUSTOMER (ID, NAME) VALUES (4, 'held')"),
    );
    assert_eq!(
        rows(&run(
            &mut other,
            &format!("SELECT COUNT(*) FROM {p}_CUSTOMER")
        )),
        json!([[3]])
    );
    // an error inside leaves it open; a savepoint is the server's own statement
    assert!(try_run(&mut s, "SELECT * FROM SC_FA_NOPE").is_err());
    assert_eq!(s.transaction_state(stop), TxState::Active);
    run(&mut s, "SAVEPOINT a");
    run(
        &mut s,
        &format!("INSERT INTO {p}_CUSTOMER (ID, NAME) VALUES (5, 'gone')"),
    );
    run(&mut s, "ROLLBACK TO SAVEPOINT a");
    run(&mut s, "COMMIT");
    assert_eq!(s.transaction_state(stop), TxState::Idle);
    assert_eq!(
        rows(&run(
            &mut other,
            &format!("SELECT COUNT(*) FROM {p}_CUSTOMER")
        )),
        json!([[4]])
    );
    run(&mut s, "SET TRANSACTION");
    run(&mut s, &format!("DELETE FROM {p}_ORDER"));
    run(&mut s, "ROLLBACK");
    assert_eq!(
        rows(&run(&mut s, &format!("SELECT COUNT(*) FROM {p}_ORDER"))),
        json!([[3]])
    );
    // nothing open: these two say nothing and do nothing
    run(&mut s, "COMMIT");
    run(&mut s, "ROLLBACK");
    drop(other);
    unshop(&mut s, p);
}

