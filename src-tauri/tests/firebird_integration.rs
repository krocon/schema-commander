const PW: &str = "Sc-test-003!";
const K: DbKind = DbKind::Firebird;

fn profile() -> Profile {
    Profile {
        id: "t".into(),
        name: "Test".into(),
        kind: K,
        host: "127.0.0.1".into(),
        port: 23050,
        database: "/var/lib/firebird/data/shop.fdb".into(),
        user: "shop".into(),
        tls: TlsMode::Off,
        folder: String::new(),
        color: 1,
        save_password: false,
        protection: guard::Protection::Free,
        label: String::new(),
        ca_file: String::new(),
        client_cert: String::new(),
        client_key: String::new(),
        ssh: None,
    }
}

fn open() -> Box<dyn Session> {
    connect(&profile(), Some(&Secret::new(PW)), &|| false).unwrap()
}

fn try_run(s: &mut Box<dyn Session>, sql: &str) -> Result<QueryResult, AppError> {
    s.query(sql, Limits::rows(MAX_ROWS), &|| false)
}

fn run(s: &mut Box<dyn Session>, sql: &str) -> QueryResult {
    try_run(s, sql).unwrap_or_else(|e| panic!("{sql}: {e}"))
}

fn rows(r: &QueryResult) -> Value {
    serde_json::to_value(&r.rows).unwrap()
}

fn try_bound(
    s: &mut Box<dyn Session>,
    sql: &str,
    params: &[Bind],
) -> Result<QueryResult, AppError> {
    let mut sink = VecSink::new(MAX_ROWS);
    let outcome = s.execute_bound(sql, params, Limits::rows(MAX_ROWS), &mut sink, &|| false)?;
    Ok(QueryResult {
        columns: outcome.columns,
        rows: sink.rows,
        truncated: outcome.truncated,
        rows_affected: outcome.rows_affected,
        elapsed_ms: outcome.elapsed_ms,
    })
}

fn bound(s: &mut Box<dyn Session>, sql: &str, params: &[Bind]) -> QueryResult {
    try_bound(s, sql, params).unwrap_or_else(|e| panic!("{sql}: {e}"))
}

/// Tables of a test's own (`p` in their names, upper case as Firebird keeps them).
fn shop(s: &mut Box<dyn Session>, p: &str) {
    unshop(s, p);
    for sql in [
        format!(
            "CREATE TABLE {p}_CUSTOMER (ID INTEGER NOT NULL PRIMARY KEY, NAME VARCHAR(50) NOT NULL, COUNTRY CHAR(2) DEFAULT 'DE', NOTE BLOB SUB_TYPE TEXT)"
        ),
        format!(
            "CREATE TABLE {p}_ORDER (ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, CUSTOMER_ID INTEGER NOT NULL, PLACED_AT DATE, TOTAL NUMERIC(10,2), \"select\" VARCHAR(10), CONSTRAINT {p}_FK FOREIGN KEY (CUSTOMER_ID) REFERENCES {p}_CUSTOMER (ID))"
        ),
        format!("CREATE INDEX {p}_ORDER_DAY ON {p}_ORDER (PLACED_AT)"),
        format!("CREATE VIEW {p}_BIG AS SELECT ID, TOTAL FROM {p}_ORDER WHERE TOTAL > 100"),
        format!(
            "CREATE TRIGGER {p}_TOUCH FOR {p}_CUSTOMER ACTIVE BEFORE UPDATE AS BEGIN IF (NEW.NAME = 'trigger') THEN NEW.NOTE = 'touched'; END"
        ),
        format!("INSERT INTO {p}_CUSTOMER (ID, NAME, COUNTRY) VALUES (1, 'Ada Lindqvist', 'SE')"),
        format!(
            "INSERT INTO {p}_CUSTOMER (ID, NAME, COUNTRY) VALUES (2, 'Bruno 100% Ferrari_x', 'IT')"
        ),
        format!(
            "INSERT INTO {p}_ORDER (ID, CUSTOMER_ID, PLACED_AT, TOTAL, \"select\") VALUES (1, 1, '2026-01-10', 250, '')"
        ),
        format!(
            "INSERT INTO {p}_ORDER (ID, CUSTOMER_ID, PLACED_AT, TOTAL, \"select\") VALUES (2, 1, '2026-02-11', 40.5, 'x')"
        ),
        format!(
            "INSERT INTO {p}_ORDER (ID, CUSTOMER_ID, PLACED_AT, TOTAL) VALUES (3, 2, '2026-03-12', NULL)"
        ),
    ] {
        run(s, &sql);
    }
}

fn unshop(s: &mut Box<dyn Session>, p: &str) {
    for sql in [
        format!("DROP VIEW {p}_BIG"),
        format!("DROP TABLE {p}_ORDER"),
        format!("DROP TABLE {p}_CUSTOMER"),
    ] {
        let _ = try_run(s, &sql);
    }
}

