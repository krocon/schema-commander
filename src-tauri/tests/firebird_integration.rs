    assert_eq!(found.len(), 1);
    assert_eq!(found[0].name, "SC_FM_ORDER");
    assert!(
        meta::search(s.as_mut(), K, "fm%ord", stop)
            .unwrap()
            .is_empty()
    );

    let mut index = names::read_objects(s.as_mut(), K, stop).unwrap();
